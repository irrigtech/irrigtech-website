// Builds the chatbot's knowledge file from the published English IrrigTech pages.
//
// The assistant may only answer from this text, so it is generated straight from
// the site's own HTML (the <main> content of each page) rather than written by hand.
// Re-run it whenever page content changes:   npm run build:knowledge
//
// Output: netlify/functions/chat/knowledge.mjs (committed, so every change to what
// the bot "knows" shows up in a reviewable git diff).

import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// English pages only: the DE/FR pages are translations of the same content, and
// the model answers in the visitor's language. Order = most useful first.
const PAGES = [
  ["/", "index.html"],
  ["/solutions.html", "solutions.html"],
  ["/platform.html", "platform.html"],
  ["/how-it-works.html", "how-it-works.html"],
  ["/devices.html", "devices.html"],
  ["/iot-sensor-node.html", "iot-sensor-node.html"],
  ["/soil-moisture-sensor.html", "soil-moisture-sensor.html"],
  ["/smart-valve-controller.html", "smart-valve-controller.html"],
  ["/pump-controller.html", "pump-controller.html"],
  ["/field-gateway.html", "field-gateway.html"],
  ["/software.html", "software.html"],
  ["/pricing.html", "pricing.html"],
  ["/about.html", "about.html"],
  ["/contact.html", "contact.html"],
  ["/blog.html", "blog.html"],
  ["/privacy.html", "privacy.html"],
  ["/terms.html", "terms.html"],
];

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", mdash: "—", ndash: "–", hellip: "…", rsquo: "’", lsquo: "‘", rdquo: "”", ldquo: "“", copy: "©", middot: "·", rarr: "→", times: "×", deg: "°" };

function decode(s) {
  return s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m);
}

function htmlToText(html) {
  const main = html.match(/<main[\s\S]*?<\/main>/i)?.[0];
  if (!main) throw new Error("no <main> element");
  let t = main
    .replace(/<(script|style|svg|noscript|form|template)\b[\s\S]*?<\/\1>/gi, " ")
    .replace(/<!--[\s\S]*?-->/g, " ")
    .replace(/<img\b[^>]*\balt="([^"]+)"[^>]*>/gi, " ")
    .replace(/<h([1-6])\b[^>]*>/gi, (_, n) => `\n\n${"#".repeat(Math.min(Number(n) + 1, 6))} `)
    .replace(/<\/h[1-6]>/gi, "\n")
    .replace(/<li\b[^>]*>/gi, "\n- ")
    .replace(/<(br|hr)\b[^>]*>/gi, "\n")
    .replace(/<\/(p|div|section|article|ul|ol|table|tr|blockquote|dd|dl|figure|header)>/gi, "\n")
    .replace(/<\/(td|th|dt)>/gi, " | ")
    .replace(/<[^>]+>/g, " ");
  t = decode(t)
    .split("\n")
    .map((l) => l.replace(/[ \t ]+/g, " ").trim())
    .filter((l, i, a) => l && !(l === "-" || (l.startsWith("- ") && l.length < 3)))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n");
  return t.trim();
}

const parts = [];
for (const [url, file] of PAGES) {
  const html = readFileSync(path.join(root, file), "utf8");
  const title = decode(html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] ?? file).trim();
  parts.push(`<page url="https://irrigtech.com${url}" title="${title.replace(/"/g, "'")}">\n${htmlToText(html)}\n</page>`);
}

const knowledge = parts.join("\n\n");
const sha = createHash("sha256").update(knowledge).digest("hex").slice(0, 12);
const out =
  `// GENERATED by scripts/build-knowledge.mjs from the English IrrigTech pages — do not edit by hand.\n` +
  `// Pages: ${PAGES.length} · characters: ${knowledge.length} · sha256: ${sha}\n` +
  `export const KNOWLEDGE_VERSION = ${JSON.stringify(sha)};\n` +
  `export const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`;

writeFileSync(path.join(root, "netlify/functions/chat/knowledge.mjs"), out, "utf8");
console.log(`knowledge.mjs written: ${PAGES.length} pages, ${knowledge.length} chars (~${Math.round(knowledge.length / 4)} tokens), sha ${sha}`);
